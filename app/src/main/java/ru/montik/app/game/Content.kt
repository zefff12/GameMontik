enum class Slot(val title: String) { HEAD("Голова"), BODY("Одежда"), FEET("Обувь") }

/** Три ценовых уровня одежды. */
enum class Tier(val title: String, val appearancePercent: Int) {
    SIMPLE("Простая", 0),
    MIDDLE("Средняя", 3),
    RICH("Богатая", 6)
}

data class ClothingItem(
    val id: String,
    val name: String,
    val emoji: String,
    val slot: Slot,
    val tier: Tier,
    val price: Int,
    /** Сколько ночей вещь прослужит. */
    val durabilityDays: Int
)

data class FoodItem(
    val id: String,
    val name: String,
    val emoji: String,
    val price: Int,
    val food: Int,
    val water: Int
)

