// ───────────────────────────── Медали ─────────────────────────────

/**
 * Медаль — заметная награда за важный шаг. В отличие от навыков, медаль даётся один раз и навсегда.
 * [earned] проверяет только те показатели, которые не убывают, поэтому полученная медаль уже не пропадёт.
 */
data class Medal(
    val id: String,
    val emoji: String,
    val title: String,
    val hint: String,
    val earned: (GameState) -> Boolean
)

object Medals {
    /** Метки, которые игра ставит навсегда: по ним выдаются медали за то, что потом можно потратить. */
    const val STYLE_THREE = "style_three"
    const val DEPOSIT_MADE = "deposit_made"
    const val LOAN_REPAID = "loan_repaid"

    val all: List<Medal> = listOf(
        Medal("first_pay", "💰", "Первая зарплата", "Отработать первую смену") { it.shifts >= 1 },
        Medal("smart", "🧮", "Умная голова", "Верно решить 5 заданий на смене") { it.tasksCorrect >= 5 },
        Medal("style", "👕", "Модник", "Надеть три вещи сразу") { STYLE_THREE in it.milestones },
        Medal("saver", "🛟", "Запасливый", "Накопить полную подушку безопасности") { "cushion_ready" in it.milestones },
        Medal("depositor", "🏦", "Вкладчик", "Открыть вклад в банке") { DEPOSIT_MADE in it.milestones },
        Medal("honest", "💳", "Честный должник", "Полностью вернуть кредит") { LOAN_REPAID in it.milestones },
        Medal("traveler", "🚂", "Путешественник", "Съездить в первый город") { it.completedTrips.isNotEmpty() },
        Medal("geographer", "🗺", "Знаток России", "Побывать в Москве, Казани и Санкт-Петербурге") {
            listOf("moscow", "kazan", "spb").all { id -> id in it.completedTrips }
        },
        Medal("sea", "🌊", "Отпускник", "Накопить 500 монет и съездить к морю в Сочи") { "sochi" in it.completedTrips },
        Medal("week", "📅", "Неделя самостоятельности", "Прожить 7 игровых дней") { it.day >= 7 },
        Medal("scholar", "🎓", "Всезнайка", "Узнать все финансовые темы игры") {
            it.seenLessons.size >= Lesson.values().size
        }
    )

    fun byId(id: String): Medal? = all.firstOrNull { it.id == id }

    /** Все медали, заработанные к этому моменту. */
    fun earned(state: GameState): List<Medal> = all.filter { it.earned(state) }
}
