// ───────────────────── Сценарии «ситуация → выбор» ─────────────────────

enum class Rating(val title: String) {
    GREAT("Отличный выбор!"),
    OK("Неплохо"),
    BAD("Можно лучше")
}

/**
 * Один вариант выбора.
 * [coins] < 0 — цена (нужно, чтобы хватало денег), [loss] — принудительная потеря (берётся, сколько есть в кошельке).
 * Положительные значения [energy]/[food]/[water] — прибавка, отрицательные — убыль.
 */
data class Choice(
    val text: String,
    val rating: Rating,
    val outcome: String,
    val explanation: String,
    val coins: Int = 0,
    val loss: Int = 0,
    val energy: Int = 0,
    val food: Int = 0,
    val water: Int = 0,
    val skill: Skill? = null,
    val skillPoints: Int = 0,
    val prepaidNight: Boolean = false,
    /** Трата обязательная (еда, ночлег, починка), а не желаемая: так она попадёт в план. */
    val need: Boolean = false,
    /** Как меняется настроение Монтика. */
    val mood: Int = 0,
    /** Сколько монет сразу отложить (в копилку на цель, а если цели нет — в подушку безопасности). */
    val save: Int = 0
)

data class Scenario(
